// Writes app/js/build-info.js with the version and GitHub repo.
// In GitHub Actions the repo comes from GITHUB_REPOSITORY automatically.
const fs = require("fs");
const path = require("path");

const pkg = require("../package.json");
let repo = process.env.GITHUB_REPOSITORY || "";
if (!repo && pkg.repository) {
  const url = typeof pkg.repository === "string" ? pkg.repository : pkg.repository.url || "";
  const m = url.match(/github\.com[:/]([^/]+\/[^/.]+)/);
  if (m) repo = m[1];
}
if (/YOUR-GITHUB-USERNAME/i.test(repo)) repo = "";
const info = { version: pkg.version, repo, built: new Date().toISOString().slice(0, 10) };
const out = path.join(__dirname, "..", "app", "js", "build-info.js");
fs.writeFileSync(out, `// Generated by scripts/build-info.js\nwindow.STE_BUILD = ${JSON.stringify(info)};\n`);
console.log("build-info:", info);
